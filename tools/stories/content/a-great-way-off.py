    "The hinge is one clause in verse 20: <b>&#8220;when he was yet a great way off, his father saw "
    "him.&#8221;</b> Everything the son planned to trade for his welcome &#8212; the confession, the verdict on "
    "himself, the offer to work as a hired hand &#8212; arrives after he is already being kissed. The "
    "father sees first, runs first, and forgives before a word of the speech is spoken; the third "
    "line of that speech never gets said at all. That is what makes the forgiveness total rather "
    "than transactional: it was not bought. And the parable then turns and asks the same thing of "
    "the other son, who never left, never sinned as spectacularly, and is standing outside the same "
    "door at the end &#8212; unanswered, because the question is not his to answer."
