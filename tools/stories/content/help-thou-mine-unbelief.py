    "the most privileged sight in Mark — three disciples on a mountain, raiment whiter than any "
    "fuller could make it, Elias and Moses, a voice out of the cloud — against a valley where "
    "the rest of the disciples could not help a child. The three came down unable to say what "
    "they had seen and asking what rising from the dead should mean; the others were arguing "
    "with scribes over a failure. The confession that turns the story comes from neither group. "
    "It comes from a father who began with “if thou canst,” heard it handed back to him, and "
    "answered with the truth about himself: faith and unbelief at once. It is the only time in "
    "the passage anyone calls Jesus Lord, and it is enough — the boy everyone called dead is "
    "lifted up and arose. The voice on the mountain said <i>hear him</i>. The man in the valley "
    "is the one who was heard."
