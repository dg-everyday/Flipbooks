THEME = (
    "The hinge of the whole account is three words in verse 18: <b>but if not</b>. The three Hebrews "
    "make two separate claims and keep them carefully apart. The first is about God's power &#8212; He is "
    "able to deliver us. The second is about their own obedience &#8212; and it does not depend on the "
    "first. Deliverance would vindicate their faith; it is not the reason for it. That is why the fire "
    "is allowed to be real, why the soldiers really die, and why the fourth figure appears "
    "<i>inside</i> the furnace rather than outside it. God does not answer the king's question "
    "(&#8220;who is that God that shall deliver you out of my hands?&#8221;) by keeping His servants out of the "
    "fire. He answers it by being in there with them."
)

