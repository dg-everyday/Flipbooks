        "The chapter begins one verse early, on the last line of the one before it. “And they were "
        "both naked, the man and his wife, and were not ashamed.” It is a plain sentence about two "
        "people with nothing to hide from each other or from anyone else. Keep the word "
        "<i>naked</i> in mind. It comes back three more times in the next eleven verses, and each "
        "time it means something different.",

